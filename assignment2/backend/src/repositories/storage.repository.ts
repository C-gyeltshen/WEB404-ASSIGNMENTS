import { env } from "../config/env.js";
import { AppError } from "../lib/errors.js";

/**
 * Supabase Storage accessed over its REST API (no supabase-js SDK).
 *
 *   Upload       POST   /storage/v1/object/{bucket}/{key}
 *   Signed URL   POST   /storage/v1/object/sign/{bucket}/{key}   { expiresIn }
 *   Delete       DELETE /storage/v1/object/{bucket}               { prefixes: [key] }
 *
 * Runs ONLY on the server: the secret key bypasses Row Level Security and
 * must never be sent to the browser.
 */
const STORAGE_URL = `${env.SUPABASE_URL}/storage/v1`;
const BUCKET = encodeURIComponent(env.SUPABASE_STORAGE_BUCKET);

function authHeaders(): Record<string, string> {
  const key = env.SUPABASE_SECRET_KEY;
  const headers: Record<string, string> = { apikey: key };
  // Legacy service_role keys are JWTs (start with "eyJ") and also go in
  // Authorization. New sb_secret_... keys are not JWTs: send them as apikey only.
  if (key.startsWith("eyJ")) headers.Authorization = `Bearer ${key}`;
  return headers;
}

/** Keys are generated by the server ("<uuid>/<uuid>.png"). Encode each segment anyway. */
function encodeKey(key: string): string {
  return key.split("/").map(encodeURIComponent).join("/");
}

async function failure(op: string, res: Response): Promise<never> {
  // Log the provider's message server-side; never forward it to the client.
  const body = await res.text().catch(() => "");
  console.error(`[storage] ${op} failed: ${res.status} ${body.slice(0, 300)}`);
  throw new AppError(502, "File storage is unavailable. Please try again.", "STORAGE_ERROR");
}

export const storageRepository = {
  async upload(key: string, bytes: Buffer, contentType: string): Promise<void> {
    const res = await fetch(`${STORAGE_URL}/object/${BUCKET}/${encodeKey(key)}`, {
      method: "POST",
      headers: {
        ...authHeaders(),
        "Content-Type": contentType, // server-detected type, not the client's header
        "x-upsert": "false",         // never overwrite an existing object
        "Cache-Control": "no-store",
      },
      body: new Uint8Array(bytes),
      signal: AbortSignal.timeout(30_000),
    });
    if (!res.ok) await failure("upload", res);
  },

  /** Short-lived URL that forces download (Content-Disposition: attachment). */
  async createSignedDownloadUrl(key: string, downloadName: string, expiresIn: number): Promise<string> {
    const res = await fetch(`${STORAGE_URL}/object/sign/${BUCKET}/${encodeKey(key)}`, {
      method: "POST",
      headers: { ...authHeaders(), "Content-Type": "application/json" },
      body: JSON.stringify({ expiresIn }),
      signal: AbortSignal.timeout(10_000),
    });
    if (!res.ok) await failure("sign", res);

    const data = (await res.json()) as { signedURL?: string };
    if (!data.signedURL) await failure("sign (no signedURL)", res);

    // signedURL is relative to /storage/v1, e.g. "/object/sign/uploads/a/b.png?token=..."
    const url = new URL(`${STORAGE_URL}${data.signedURL}`);
    url.searchParams.set("download", downloadName);
    return url.toString();
  },

  async remove(key: string): Promise<void> {
    const res = await fetch(`${STORAGE_URL}/object/${BUCKET}`, {
      method: "DELETE",
      headers: { ...authHeaders(), "Content-Type": "application/json" },
      body: JSON.stringify({ prefixes: [key] }),
      signal: AbortSignal.timeout(10_000),
    });
    if (!res.ok) await failure("delete", res);
  },
};
